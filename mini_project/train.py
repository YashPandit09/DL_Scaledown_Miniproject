"""
SpaceGen AI - Training Loop (Simplified for Mini Project)

This file shows HOW both models are trained:
  1. CVAE training: Reconstruction Loss + KL Divergence (with beta-annealing)
  2. CNN Evaluator training: BCE (valid/invalid) + MSE (quality score)

To keep this simple and runnable, we use SYNTHETIC random data.
In the real project, data is generated by the rule-based room generator.
"""

import torch
import torch.optim as optim
from torch.utils.data import TensorDataset, DataLoader
from model import CVAE, CNNEvaluator, cvae_loss, evaluator_loss

# ─────────────────────────────────────────────────────────────────────────────
# Hyperparameters
# ─────────────────────────────────────────────────────────────────────────────
NUM_ITEMS   = 6        # furniture slots in a living room
INPUT_DIM   = NUM_ITEMS * 4   # (x, y, sin_rot, cos_rot) — simplified
COND_DIM    = 12       # room width, depth, door encoding
LATENT_DIM  = 16       # size of latent space z
HIDDEN      = 256      # hidden layer size
PIXELS      = 64       # CNN input image size

BATCH_SIZE  = 64
EPOCHS      = 10
LR          = 1e-3
BETA_MAX    = 0.1      # KL weight at end of annealing
ANNEAL_EP   = 5        # number of epochs to ramp beta from 0 -> BETA_MAX


# ─────────────────────────────────────────────────────────────────────────────
# Synthetic Data (replace with real dataset in the full project)
# ─────────────────────────────────────────────────────────────────────────────
def make_synthetic_data(n=2000):
    """Create random fake layout data for demonstration."""
    x_layouts   = torch.rand(n, INPUT_DIM)          # furniture positions
    conditions  = torch.rand(n, COND_DIM)            # room specs
    pos_true    = torch.rand(n, NUM_ITEMS, 2)        # ground truth positions
    rot_true    = torch.randint(0, 4, (n, NUM_ITEMS))# ground truth rotations
    mask        = torch.ones(n, NUM_ITEMS)            # all items present
    images      = torch.rand(n, 4, PIXELS, PIXELS)   # floorplan images
    valid_true  = torch.randint(0, 2, (n,)).float()  # 0=invalid, 1=valid
    score_true  = torch.rand(n)                       # quality score [0,1]
    return x_layouts, conditions, pos_true, rot_true, mask, images, valid_true, score_true


# ─────────────────────────────────────────────────────────────────────────────
# Train CVAE
# ─────────────────────────────────────────────────────────────────────────────
def train_cvae(cvae, dataloader, epochs=EPOCHS):
    optimizer = optim.Adam(cvae.parameters(), lr=LR)
    print("\n" + "=" * 55)
    print("  Training CVAE (Conditional Variational Autoencoder)")
    print("=" * 55)
    print(f"  Optimizer  : Adam (lr={LR})")
    print(f"  Latent dim : {LATENT_DIM}   Hidden: {HIDDEN}")
    print(f"  Beta anneal: 0.0 -> {BETA_MAX} over {ANNEAL_EP} epochs")
    print()

    for epoch in range(1, epochs + 1):
        # Beta-annealing: linearly ramp KL weight from 0 -> BETA_MAX
        # WHY: Starting with beta=0 lets decoder learn first.
        #      Jumping straight to full KL weight causes posterior collapse.
        beta = min(BETA_MAX, BETA_MAX * epoch / ANNEAL_EP)

        cvae.train()
        total_loss = pos_l = rot_l = kl_l = 0.0
        for x, cond, pos_t, rot_t, mask in dataloader:
            optimizer.zero_grad()

            # Forward pass
            pos_pred, rot_pred, mu, logvar = cvae(x, cond)

            # Loss: Reconstruction + beta * KL
            loss, p, r, kl = cvae_loss(pos_pred, pos_t, rot_pred, rot_t, mu, logvar, mask, beta)

            loss.backward()
            optimizer.step()

            total_loss += loss.item()
            pos_l += p.item(); rot_l += r.item(); kl_l += kl.item()

        n = len(dataloader)
        print(f"  Epoch {epoch:02d}/{epochs}  beta={beta:.3f}  "
              f"loss={total_loss/n:.4f}  pos={pos_l/n:.4f}  rot={rot_l/n:.4f}  kl={kl_l/n:.4f}")

    print("\n  CVAE training done!")
    return cvae


# ─────────────────────────────────────────────────────────────────────────────
# Train CNN Evaluator
# ─────────────────────────────────────────────────────────────────────────────
def train_evaluator(evaluator, dataloader, epochs=EPOCHS):
    optimizer = optim.Adam(evaluator.parameters(), lr=LR)
    print("\n" + "=" * 55)
    print("  Training CNN Evaluator")
    print("=" * 55)
    print(f"  Optimizer : Adam (lr={LR})")
    print(f"  Input     : (B, 4, {PIXELS}, {PIXELS}) floorplan image")
    print(f"  Outputs   : P(valid) [BCE]  +  Quality Score [MSE]")
    print()

    for epoch in range(1, epochs + 1):
        evaluator.train()
        total_loss = bce_l = mse_l = 0.0
        for imgs, valid_t, score_t in dataloader:
            optimizer.zero_grad()

            valid_logit, score_pred = evaluator(imgs)
            loss, bce, mse = evaluator_loss(valid_logit, score_pred, valid_t, score_t)

            loss.backward()
            optimizer.step()

            total_loss += loss.item()
            bce_l += bce.item(); mse_l += mse.item()

        n = len(dataloader)
        print(f"  Epoch {epoch:02d}/{epochs}  loss={total_loss/n:.4f}  "
              f"bce={bce_l/n:.4f}  mse={mse_l/n:.4f}")

    print("\n  CNN Evaluator training done!")
    return evaluator


# ─────────────────────────────────────────────────────────────────────────────
# Main
# ─────────────────────────────────────────────────────────────────────────────
if __name__ == "__main__":
    print("SpaceGen AI — Simplified Training Demo")
    print("Using synthetic data (no dataset files needed)\n")

    # Generate synthetic data
    x_lay, conds, pos_t, rot_t, mask, imgs, valid_t, score_t = make_synthetic_data(2000)

    # --- CVAE DataLoader ---
    cvae_ds = TensorDataset(x_lay, conds, pos_t, rot_t, mask)
    cvae_dl = DataLoader(cvae_ds, batch_size=BATCH_SIZE, shuffle=True)

    # --- Evaluator DataLoader ---
    eval_ds = TensorDataset(imgs, valid_t, score_t)
    eval_dl = DataLoader(eval_ds, batch_size=BATCH_SIZE, shuffle=True)

    # --- Train CVAE ---
    cvae_model = CVAE(INPUT_DIM, COND_DIM, NUM_ITEMS, LATENT_DIM, HIDDEN)
    cvae_model = train_cvae(cvae_model, cvae_dl)

    # --- Train CNN Evaluator ---
    cnn_model = CNNEvaluator(in_channels=4, pixels=PIXELS)
    cnn_model = train_evaluator(cnn_model, eval_dl)

    # --- Save weights ---
    torch.save(cvae_model.state_dict(), "cvae_simple.pt")
    torch.save(cnn_model.state_dict(),  "evaluator_simple.pt")
    print("\nSaved: cvae_simple.pt, evaluator_simple.pt")
